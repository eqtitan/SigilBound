// Generates the Godot demo's data tables from the WEB game's own files, so heroes, skills and
// hero looks never drift by hand-copying:
//   godot/scripts/generated/web_data.gd   <- public/game/data.js (heroes, skills, elements, rarity,
//                                             roles, effects, campaign curve, gear, summoning)
//   godot/scripts/generated/looks_data.gd <- public/game/art.js (SKIN, LOOKS) and
//                                             game3d/three3d.mjs (BASE, BODY, ROLES)
// The rules that use these tables (stats, battle engine) are hand-ported GDScript, checked
// against the web code by godot/tests (fixtures from make-fixtures.cjs).
// Run from the repo root after the web data changes:  node godot/tools/make-generated.cjs
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "../..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const outDir = path.join(root, "godot/scripts/generated");
fs.mkdirSync(outDir, { recursive: true });

// ---------- data.js ----------
const ctx = { Object, Array, Math, Date, JSON };
vm.createContext(ctx);
vm.runInContext(read("public/game/data.js") + `
;globalThis.__d = { ELEMENTS, ELEMENT_KEYS, RARITY, RARITY_KEYS, ROLES, EFFECTS, HEROES, STARTERS, CHAPTERS, STAGES_PER_CHAPTER,
  ENEMY_CURVE, GEAR_SLOTS, GEAR_SLOT_KEYS, GEAR_SETS, GEAR_SET_KEYS, SUBSTATS, SHARDS, GEAR_MAX_LEVEL, MAX_STARS };`, ctx);
const D = ctx.__d;
const strip = (o, keys) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).filter(([kk]) => !keys.includes(kk)))]));
// GDScript reads JSON literals as-is; "icon" fields hold emoji the default font can't draw, so they are left out.
const lit = (v) => JSON.stringify(v, null, 0);
const data = [
  "# GENERATED by godot/tools/make-generated.cjs from public/game/data.js. Do not edit by hand.",
  "class_name WebData",
  "",
  `const ELEMENTS = ${lit(strip(D.ELEMENTS, ["icon"]))}`,
  `const ELEMENT_KEYS = ${lit(D.ELEMENT_KEYS)}`,
  `const RARITY = ${lit(D.RARITY)}`,
  `const RARITY_KEYS = ${lit(D.RARITY_KEYS)}`,
  `const ROLES = ${lit(strip(D.ROLES, ["icon"]))}`,
  `const EFFECTS = ${lit(strip(D.EFFECTS, ["icon"]))}`,
  `const HEROES = [\n${D.HEROES.map((h) => "\t" + lit(h)).join(",\n")}\n]`,
  `const STARTERS = ${lit(D.STARTERS)}`,
  `const CHAPTERS = ${lit(D.CHAPTERS)}`,
  `const STAGES_PER_CHAPTER = ${D.STAGES_PER_CHAPTER}`,
  `const ENEMY_CURVE = ${lit(D.ENEMY_CURVE)}`,
  `const GEAR_SLOTS = ${lit(strip(D.GEAR_SLOTS, ["icon"]))}`,
  `const GEAR_SLOT_KEYS = ${lit(D.GEAR_SLOT_KEYS)}`,
  `const GEAR_SETS = ${lit(strip(D.GEAR_SETS, ["icon"]))}`,
  `const GEAR_SET_KEYS = ${lit(D.GEAR_SET_KEYS)}`,
  `const SUBSTATS = ${lit(D.SUBSTATS)}`,
  `const SHARDS = ${lit(strip(D.SHARDS, ["icon"]))}`,
  `const GEAR_MAX_LEVEL = ${D.GEAR_MAX_LEVEL}`,
  `const MAX_STARS = ${D.MAX_STARS}`,
  "",
];
fs.writeFileSync(path.join(outDir, "web_data.gd"), data.join("\n"));

// ---------- art.js / three3d.mjs ----------
function grab(src, name) {
  const i = src.indexOf(`const ${name} = {`);
  if (i < 0) throw new Error("missing " + name);
  let depth = 0;
  const j = src.indexOf("{", i);
  for (let k = j; k < src.length; k++) {
    if (src[k] === "{") depth++;
    else if (src[k] === "}") { depth--; if (!depth) return eval("(" + src.slice(j, k + 1) + ")"); }
  }
  throw new Error("unterminated " + name);
}
const art = read("public/game/art.js"), t3 = read("game3d/three3d.mjs");
const LOOKS = grab(art, "LOOKS"), SKIN = grab(art, "SKIN");
const BASE = grab(t3, "BASE"), BODY = grab(t3, "BODY"), ROLES = grab(t3, "ROLES"), PARTMESH = grab(t3, "PARTMESH");
const looks = [
  "# GENERATED by godot/tools/make-generated.cjs from public/game/art.js (SKIN, LOOKS) and",
  "# game3d/three3d.mjs (BASE, BODY, ROLES, PARTMESH). Do not edit by hand.",
  "class_name LooksData",
  "",
  `const SKIN = ${lit(SKIN)}`,
  `const LOOKS = {\n${Object.entries(LOOKS).map(([k, v]) => `\t${lit(k)}: ${lit(v)}`).join(",\n")}\n}`,
  `const BASE = ${lit(BASE)}`,
  `const BODY = {\n${Object.entries(BODY).map(([k, v]) => `\t${lit(k)}: ${lit(v)}`).join(",\n")}\n}`,
  `const ROLES = ${lit(ROLES)}`,
  `const PARTMESH = ${lit(PARTMESH)}`,
  "",
];
fs.writeFileSync(path.join(outDir, "looks_data.gd"), looks.join("\n"));
console.log(`web_data.gd: ${D.HEROES.length} heroes; looks_data.gd: ${Object.keys(LOOKS).length} looks, ${Object.keys(BODY).length} bodies`);
