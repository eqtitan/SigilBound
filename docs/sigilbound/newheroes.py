"""Phase H: brings the owner-approved new heroes (docs/sigilbound/concepts/new_heroes.json) into the game.

    python3 docs/sigilbound/newheroes.py --count N          # write the first N heroes into the game data
    python3 docs/sigilbound/newheroes.py --count N --tune   # ...and balance them (team-swap sims, aim 40-60%)

Writes, between the generated-block markers:
- Core/GameData.cs  Heroes: HeroDef entries (skills from the design; damage, shields and heals scaled by
  the hero's power factor in concepts/tuning.json);
- Core/Looks.cs     Table: a stand-in look for the code-built model (Hollow enemies, fallback);
- docs/sigilbound/ROSTER.md: a phase H table (RosterTests require every hero to be listed).
The tuner runs `dotnet run --project unity/Tests~ -- balance <ids>` and nudges each power factor until
the hero wins 40-60% against the classic hero(es) of its rarity and role.
"""
import argparse, json, os, re, subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
CON = os.path.join(ROOT, "docs", "sigilbound", "concepts")
GD = os.path.join(ROOT, "unity", "Assets", "Sigilbound", "Core", "GameData.cs")
LK = os.path.join(ROOT, "unity", "Assets", "Sigilbound", "Core", "Looks.cs")
RO = os.path.join(ROOT, "docs", "sigilbound", "ROSTER.md")
TUNE = os.path.join(CON, "tuning.json")
G0, G1 = "            // --- phase H: generated by", "            // --- end phase H ---"
L0, L1 = "            // --- phase H looks: generated by", "            // --- end phase H looks ---"
FX = {"AtkUp", "DefUp", "SpdUp", "Regen", "Shield", "Taunt", "AtkDown", "DefDown", "Slow", "Poison", "Stun", "Heal", "Tm", "TmDrain",
      "Cleanse", "Strip", "Burn", "Pull", "Counter", "Revive"}
PROPS = ["sword", "katana", "daggers", "spear", "trident", "hammer", "club", "staff", "orb", "bow", "shield", "candle", "lantern",
         "bell", "mirror", "book", "fan", "axe", "anchor", "hook", "whip", "net", "lute", "gauntlets"]
ALIASES = {"glaive": "spear", "lance": "spear", "halberd": "spear", "scythe": "spear", "pike": "spear", "maul": "hammer", "mace": "hammer",
           "flail": "club", "cudgel": "club", "rapier": "sword", "blade": "sword", "sabre": "sword", "dagger": "daggers", "knife": "daggers",
           "sickle": "daggers", "crossbow": "bow", "sceptre": "staff", "wand": "staff", "tome": "book", "harp": "lute", "umbrella": "shield",
           "door": "shield", "chakram": "daggers", "loom": "staff", "lens": "mirror", "pot": "club", "cauldron": "shield"}

def cs(x): return json.dumps(x)
def num(v): return repr(round(float(v), 4))

def prop_of(weapon):
    w = weapon.lower()
    for p in PROPS:
        if re.search(r"\b" + p.rstrip("s") + r"s?\b", w): return p
    for k, p in ALIASES.items():
        if k in w: return p
    return "staff" if any(k in w for k in ("spell", "magic", "rune")) else "sword"

def hero_cs(c, f):
    sk = []
    for s in c["skills"]:
        fx = []
        for e in s.get("effects", []):
            if e["type"] not in FX: continue
            parts = [f"Type = FxType.{e['type']}"]
            if "turns" in e: parts.append(f"Turns = {int(e['turns'])}")
            if "chance" in e: parts.append(f"Chance = {num(e['chance'])}")
            if "pct" in e:
                pct = e["pct"] * (f if e["type"] in ("Shield", "Heal") else 1)
                parts.append(f"Pct = {num(min(pct, 0.6))}")
            if "val" in e: parts.append(f"Val = {num(e['val'])}")
            if e.get("to") in ("Self", "Allies", "Enemies"): parts.append(f"To = FxTo.{e['to']}")
            fx.append("new FxDef { " + ", ".join(parts) + " }")
        p = [f"Name = {cs(s['name'])}", f"Target = Target.{s['target']}", f"Mult = {num(s['mult'] * f)}", f"Cooldown = {int(s['cooldown'])}"]
        if int(s.get("hits", 1)) != 1: p.append(f"Hits = {int(s['hits'])}")
        if s.get("scale", "Atk") != "Atk": p.append(f"Scale = Scale.{s['scale']}")
        if s.get("pierce"): p.append("Pierce = true")
        if s.get("spread"): p.append("Spread = true")
        if s.get("execute"): p.append(f"Execute = {num(s['execute'])}")
        p.append("Fx = new[] { " + ", ".join(fx) + " }" if fx else "Fx = new FxDef[0]")
        sk.append("new SkillDef { " + ", ".join(p) + " }")
    extra = ""
    m = re.search(r"FallHeal ([0-9.]+)", str(c.get("passive", "")))
    if m: extra = f", FallHeal = {num(float(m.group(1)))}"
    return (f'            new HeroDef {{ Id = {cs(c["id"])}, Name = {cs(c["name"])}, Rarity = Rarity.{c["rarity"]}, Element = Element.{c["element"]}, '
            f'Role = Role.{c["role"]}{extra}, Skills = new[] {{ ' + ", ".join(sk) + " } },")

def look_cs(c):
    pal = c.get("palette", {}); sex = c.get("sex", "male"); w = str(c.get("weapon", ""))
    o = c.get("outfit", {}); kit = " ".join(map(str, c.get("kit", []))).lower()
    base = "hooded" if sex == "female" or "hood" in str(o.get("head", "")).lower() else ("monarch" if "Knight" in str(o.get("body", "")) or "Noble" in str(o.get("body", "")) else "adventurer")
    hair = (c.get("hair") or {}).get("colour", "#3a2a1a"); style = (c.get("hair") or {}).get("style", "")
    gear = "helm" if "Armet" in str(o.get("head", "")) or "helm" in kit else "crown" if "crown" in kit else "horns" if "horn" in kit else "halo" if "halo" in kit else "none"
    skin = c.get("skin", "fair"); skin = skin if not str(skin).startswith("#") else "fair"
    fields = [f'Skin = {cs(skin)}', f'Hair = {cs(hair)}', f'Style = {cs("bald" if "bald" in style.lower() else "long" if sex == "female" else "short")}',
              f'Gear = {cs(gear)}', f'Armor = {cs(pal.get("main", "#555555"))}', f'Accent = {cs(pal.get("accent", "#cccccc"))}',
              f'Cloth = {cs(pal.get("secondary", "#333333"))}', f'Prop = {cs(prop_of(w))}', f'Glow = {cs(pal.get("glow"))}',
              f'Cape = {"true" if "cape" in kit or "cloak" in kit else "false"}', f'CapeColor = {cs(pal.get("secondary"))}',
              f'Base = {cs(base)}', f'Height = {num(c.get("body", {}).get("height", 1.0))}', 'Hide = new[] { "hood" }']
    return f'            [{cs(c["id"])}] = new HeroLook {{ ' + ", ".join(fields) + " },"

def roster_md(heroes):
    lines = ["", "## 7. Phase H: 50 new heroes (owner-approved concepts, 2026-11-26)", "",
             "Designs: `docs/sigilbound/concepts/new_heroes.json` and `NEW_HEROES.md`. Brought into the game by `docs/sigilbound/newheroes.py`, 10 per step, each balanced against the classic hero(es) of its rarity and role.", "",
             "| Id | Name | Rarity | Element | Role | Species | Concept |", "|---|---|---|---|---|---|---|"]
    for c in heroes:
        lines.append(f"| `{c['id']}` | {c['name']} | {c['rarity']} | {c['element']} | {c['role']} | {c.get('species', 'human')} | {c.get('story', '').split('.')[0]}. |")
    return "\n".join(lines) + "\n"

def replace_block(path, start, end, body):
    s = open(path).read(); i = s.index(start); i = s.index("\n", i) + 1; j = s.index(end, i)
    open(path, "w").write(s[:i] + body + s[j:])

def write(heroes, tune):
    replace_block(GD, G0, G1, "".join(hero_cs(c, tune.get(c["id"], 1.0)) + "\n" for c in heroes))
    replace_block(LK, L0, L1, "".join(look_cs(c) + "\n" for c in heroes))
    s = open(RO).read()
    k = s.find("\n## 7. Phase H")
    open(RO, "w").write((s if k < 0 else s[:k]) .rstrip("\n") + "\n" + roster_md(heroes))

def rates(ids):
    out = subprocess.run(["dotnet", "run", "--project", os.path.join(ROOT, "unity", "Tests~"), "--", "balance"] + ids,
                         capture_output=True, text=True, cwd=ROOT).stdout
    return {m.group(1): float(m.group(2)) for m in re.finditer(r"RATE (\S+) ([0-9.]+)", out)}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--count", type=int, required=True); ap.add_argument("--tune", action="store_true")
    a = ap.parse_args()
    heroes = json.load(open(os.path.join(CON, "new_heroes.json")))[: a.count]
    tune = json.load(open(TUNE)) if os.path.exists(TUNE) else {}
    write(heroes, tune)
    if a.tune:
        todo = [c["id"] for c in heroes]
        lo, hi = {}, {}   # bracket: power factors known to be too weak / too strong
        for rnd in range(14):
            r = rates(todo)
            bad = {i: v for i, v in r.items() if not 0.42 <= v <= 0.58}
            print(f"round {rnd}: " + ", ".join(f"{i} {v:.0%}" for i, v in sorted(r.items())))
            if not bad: break
            for i, v in bad.items():
                f = tune.get(i, 1.0)
                if v < 0.5: lo[i] = max(lo.get(i, 0), f)
                else: hi[i] = min(hi.get(i, 9), f)
                if i in lo and i in hi: f = (lo[i] + hi[i]) / 2              # close in once both sides are known
                else: f *= 1 + (0.5 - v) * 1.2
                tune[i] = round(max(0.3, min(2.5, f)), 4)
            json.dump(tune, open(TUNE, "w"), indent=1, sort_keys=True)
            write(heroes, tune)
            todo = list(bad)
        json.dump(tune, open(TUNE, "w"), indent=1, sort_keys=True)
    print("wrote", len(heroes), "heroes")

if __name__ == "__main__":
    main()
