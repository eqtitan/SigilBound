"""Each hero's armour class, read from the approved design's outfit, kit, signature and silhouette text
(concepts/concepts.json + concepts/new_heroes.json). Writes unity/Assets/Sigilbound/Core/Kit/HeroArmour.cs.
The client picks the hit sound by attacker weapon family x defender armour class (plate clangs and
rattles, mail jingles, leather slaps, cloth thuds). Scores: kit parts (Knight_Body_Armor, Armet, Ranger_*,
Wizard_*, robes) plus keywords in the custom text; plate needs real plate pieces, mail needs mail words.
Run: python3 docs/sigilbound/armourclass.py
"""
import json, os, re, collections
HERE = os.path.dirname(os.path.abspath(__file__))
WORDS = {
    "Plate": "plate breastplate cuirass pauldron gauntlet greave vambrace armet helm visor bevor gorget sabaton "
             "steel-plated full-plate plated armour armor",
    "Mail": "mail chainmail chain-mail hauberk ringmail ring-mail coif scale scales brigandine lamellar",
    "Leather": "leather hide fur pelt jerkin studded bracer buckskin sealskin oilskin boiled-leather harness belt strap",
    "Cloth": "robe gown dress skirt tunic silk cloth linen wool cloak shawl apron smock habit vestment sash scarf",
}
PARTS = [  # (regex over the outfit part names, class, weight)
    (r"knight[_/]body_armor", "Plate", 4), (r"armet", "Plate", 3), (r"knight[_/](arms|legs|feet)", "Plate", 1),
    (r"knight[_/]body_cloth", "Cloth", 2), (r"ranger", "Leather", 1), (r"(wizard|noble)", "Cloth", 1.5),
    (r"peasant", "Cloth", 0.6), (r"covered by robe|gown", "Cloth", 2),
]
def score(c):
    o = c.get("outfit") or {}
    parts = " ".join(str(o.get(k, "")) for k in ("arms", "body", "legs", "feet", "head")).lower()
    text = " ".join([str(o.get(k, "")) for k in ("arms", "body", "legs", "feet", "head")] + [str(a) for a in (o.get("acc") or [])]
                    + [str(k) for k in c.get("kit", [])] + [str(c.get(k, "")) for k in ("signature", "silhouette")]).lower()
    s = collections.Counter()
    for rx, cls, w in PARTS:
        s[cls] += w * len(re.findall(rx, parts))
    for cls, ws in WORDS.items():
        for w in ws.split():
            n = len(re.findall(r"\b" + re.escape(w) + r"s?\b", text))
            if w in ("armour", "armor") and re.search(r"(leather|hide|bark|bone|cloth|padded|quilted) arm(ou|o)r", text): continue
            s[cls] += n * (1.5 if cls in ("Plate", "Mail") else 1)
    return s
def klass(c):
    s = score(c)
    if s["Plate"] >= 4: return "Plate"
    if s["Mail"] >= 1.5: return "Mail"
    if s["Plate"] >= 2.5 and s["Plate"] >= s["Leather"]: return "Mail"  # some plate pieces over softer kit: mixed metal
    return "Leather" if s["Leather"] > s["Cloth"] else "Cloth"
heroes = []
for f in ("concepts.json", "new_heroes.json"):
    heroes += json.load(open(os.path.join(HERE, "concepts", f)))
rows = [(c["id"], klass(c)) for c in heroes]
cs = ["// GENERATED by docs/sigilbound/armourclass.py from each approved design's outfit and kit text. Do not edit by hand.",
      "// The client picks hit sounds by attacker weapon family x defender armour (Sound.HitOn).",
      "using System.Collections.Generic;", "", "namespace Sigilbound.Core", "{",
      "    public enum ArmourClass { Cloth, Leather, Mail, Plate }", "",
      "    public static class HeroArmour", "    {",
      "        public static readonly Dictionary<string, ArmourClass> Table = new Dictionary<string, ArmourClass>", "        {"]
cs += [f'            ["{i}"] = ArmourClass.{k},' for i, k in rows]
cs += ["        };",
       "        // Unlisted ids (enemies built from other templates): by role, defenders wear plate.",
       "        public static ArmourClass Of(string id, Role role) => Table.TryGetValue(id ?? \"\", out var k) ? k : role switch",
       "        {", "            Role.Defense => ArmourClass.Plate, Role.Attack => ArmourClass.Leather, _ => ArmourClass.Cloth,", "        };",
       "    }", "}", ""]
out = os.path.join(HERE, "..", "..", "unity", "Assets", "Sigilbound", "Core", "Kit", "HeroArmour.cs")
open(out, "w").write("\n".join(cs))
print(len(rows), "heroes:", dict(collections.Counter(k for _, k in rows).most_common()))
