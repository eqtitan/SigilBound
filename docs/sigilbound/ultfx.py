"""Signature ultimates (owner request, 2026-11-26): which hand-made ultimate clip (blenderforge/make_clips.py,
Ult_*) each Legendary and Epic hero plays for its ultimate. Writes unity/Assets/Sigilbound/Core/Kit/HeroUlts.cs.

Inputs: `dotnet run --project unity/Tests~ -- ults` (id, weapon family, prop, rarity, role, ultimate target,
multiplier, name) and each design's fx line (concepts/*.json). Rules: a support ultimate (no damage) is the
Blessing; otherwise the clip must suit the weapon family (FAMILY below); among those, the first clip whose
keyword appears in the ultimate's name or fx text wins; else a stable pick by hero id, for variety.

    python3 docs/sigilbound/ultfx.py
"""
import json, os, re, subprocess, collections, zlib
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
IMPACT = {"Ult_LeapSlam": 0.62, "Ult_Whirlwind": 0.50, "Ult_Overhead": 0.55, "Ult_DashStrike": 0.36, "Ult_Uppercut": 0.45,
          "Ult_GroundPound": 0.47, "Ult_Channel": 0.56, "Ult_Volley": 0.50, "Ult_Twirl": 0.70, "Ult_Blessing": 0.62, "Ult_TwinFlurry": 0.60}
TRAVELS = {"Ult_Whirlwind", "Ult_Overhead", "Ult_DashStrike", "Ult_Uppercut", "Ult_TwinFlurry", "Ult_LeapSlam"}   # run in on single-target melee
FAMILY = {
    "Blade": ["Ult_Overhead", "Ult_DashStrike", "Ult_Whirlwind", "Ult_Uppercut"],
    "Heavy": ["Ult_LeapSlam", "Ult_Overhead", "Ult_GroundPound", "Ult_Whirlwind"],
    "Polearm": ["Ult_DashStrike", "Ult_Whirlwind", "Ult_Uppercut", "Ult_Twirl"],
    "Daggers": ["Ult_TwinFlurry", "Ult_DashStrike", "Ult_Whirlwind"],
    "Bow": ["Ult_Volley"],
    "Caster": ["Ult_Channel", "Ult_Twirl"],
    "Support": ["Ult_Channel", "Ult_Blessing"],
    "Shield": ["Ult_LeapSlam", "Ult_Overhead", "Ult_DashStrike"],
    "Unarmed": ["Ult_GroundPound", "Ult_Uppercut", "Ult_LeapSlam"],
}
STAFFLIKE = {"staff", "spear", "trident", "glaive", "scythe", "lance"}   # Twirl needs a long haft
KEYS = {
    "Ult_LeapSlam": "leap jump meteor skyfall descend crash plunge bound",
    "Ult_Whirlwind": "spin whirl cyclone vortex sweep haft reap maelstrom whirlpool",
    "Ult_DashStrike": "dash charge rush lunge pierce blitz flash strike-through gallop drive dive raid",
    "Ult_Uppercut": "upper rising skyward launch geyser ascend",
    "Ult_GroundPound": "quake pound earth stomp tremor shatter avalanche landslide smash ground",
    "Ult_Volley": "rain volley barrage hail arrows",
    "Ult_Channel": "beam ray nova blast surge torrent flare",
    "Ult_Overhead": "chop cleave execution judgment judgement verdict sunder smite hammer",
    "Ult_TwinFlurry": "flurry thousand cuts blades dance twin",
    "Ult_Twirl": "twirl staff circle orbit",
    "Ult_Blessing": "bless hymn prayer dawn grace",
}
fx = {}
for f in ("concepts.json", "new_heroes.json"):
    for c in json.load(open(os.path.join(HERE, "concepts", f))): fx[c["id"]] = str(c.get("fx", ""))
out = subprocess.run(["dotnet", "run", "--project", os.path.join(ROOT, "unity", "Tests~"), "--", "ults"], capture_output=True, text=True, check=True).stdout
rows, counts = [], collections.Counter()
for line in out.splitlines():
    p = line.split("\t")
    if len(p) < 8: continue
    hid, fam, prop, rarity, role, target, mult, name = p[:8]
    if rarity not in ("Legendary", "Epic"): continue
    if float(mult) == 0: clip = "Ult_Blessing"
    else:
        allowed = [c for c in FAMILY.get(fam, FAMILY["Blade"]) if c != "Ult_Twirl" or prop in STAFFLIKE]
        # Only the ultimate's own words: its name, and the clause of the fx line that names it.
        clause = next((c for c in re.split(r"[;.]", fx.get(hid, "")) if name.lower() in c.lower()), "")
        text = " " + (name + " " + clause).lower()
        best = None
        for c in allowed:
            for k in KEYS[c].split():
                m = re.search(r"[^a-z]" + re.escape(k), text)
                if m and (best is None or m.start() < best[0]): best = (m.start(), c)
        # No keyword: twin blades always flurry; other families take a stable pick by hero id, for variety.
        clip = best[1] if best else "Ult_TwinFlurry" if fam == "Daggers" else allowed[zlib.crc32(hid.encode()) % len(allowed)]
    rows.append((hid, clip)); counts[clip] += 1
cs = ["// GENERATED by docs/sigilbound/ultfx.py (signature ultimates for Legendary and Epic heroes). Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace Sigilbound.Core", "{", "    public static class HeroUlts", "    {",
      "        // hero -> its ultimate clip (Ult_*, made by blenderforge/make_clips.py, in models/ubc_anims.glb)",
      "        public static readonly Dictionary<string, string> Table = new Dictionary<string, string>", "        {"]
cs += [f'            ["{h}"] = "{c}",' for h, c in rows]
cs += ["        };", "        // Normalized impact (or release) time in each clip: damage, numbers and effects land there.",
       "        public static readonly Dictionary<string, double> Impact = new Dictionary<string, double>", "        {"]
cs += [f'            ["{c}"] = {v},' for c, v in IMPACT.items()]
cs += ["        };", "        // Clips that run in to the target first on a single-target melee ultimate (the rest play in place).",
       "        public static readonly HashSet<string> Travels = new HashSet<string> { " + ", ".join(f'"{c}"' for c in sorted(TRAVELS)) + " };",
       "        public static string ClipFor(string heroId) => heroId != null && Table.TryGetValue(heroId, out var c) ? c : null;",
       "    }", "}", ""]
open(os.path.join(ROOT, "unity", "Assets", "Sigilbound", "Core", "Kit", "HeroUlts.cs"), "w").write("\n".join(cs))
print(len(rows), "heroes:", dict(counts.most_common()))
