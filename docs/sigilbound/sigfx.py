"""Phase E steps 53-55: each hero's signature effect motif, read from the approved design's `fx` line
(concepts/concepts.json + concepts/new_heroes.json). Writes unity/Assets/Sigilbound/Core/Kit/HeroSignatures.cs.
The motif is the keyword that appears FIRST in the fx text (so "green gust rings" -> Wind); a hero whose
text names none gets its element's default. Run: python3 docs/sigilbound/sigfx.py
"""
import json, os, re, collections
HERE = os.path.dirname(os.path.abspath(__file__))
KEYS = [  # motif, keywords (word starts)
    ("Wind", "gust wind breeze whirl cyclone gale tornado air"),
    ("Embers", "ember coal cinder flame fire spark heat ash burn candle soot-orange"),
    ("Water", "water splash wave droplet tide spray rain drip brine salt kelp seaweed"),
    ("Bubbles", "bubble foam froth"),
    ("Frost", "frost ice snow rime cold frozen"),
    ("Petals", "petal blossom flower rose bloom"),
    ("Leaves", "leaf vine thorn moss seed pollen bramble petal-green"),
    ("Feathers", "feather plume quill"),
    ("Stars", "stars starry star-fleck star fleck comet constellation"),
    ("Lightning", "lightning thunder storm static spark-blue bolt"),
    ("Smoke", "soot smoke mist fog haze steam"),
    ("Wisps", "wisp spirit ghost soul shade"),
    ("Bones", "bone skull grave rattl"),
    ("Mud", "mud dirt earth stone rock dust sand pebble gravel"),
    ("Runes", "rune sigil glyph seal"),
    ("Notes", "bell chime note song hymn music melody whistle"),
    ("Poison", "poison venom toxic smear"),
    ("Shards", "shard crystal glass mirror prism"),
]
FALLBACK = ("Motes", "mote light glow sun gold halo radiant shimmer")  # only when nothing more specific is named
DEFAULT = {"Flame": "Embers", "Gale": "Wind", "Tide": "Water", "Light": "Motes", "Shadow": "Wisps"}
def motif(c):
    t = " " + str(c.get("fx", "")).lower()
    best = None
    for m, ks in KEYS:
        for k in ks.split():
            mm = re.search(r"[^a-z]" + re.escape(k), t)
            if mm and (best is None or mm.start() < best[0]): best = (mm.start(), m)
    if best is None:
        for k in FALLBACK[1].split():
            mm = re.search(r"[^a-z]" + re.escape(k), t)
            if mm and (best is None or mm.start() < best[0]): best = (mm.start(), FALLBACK[0])
    return best[1] if best else DEFAULT.get(c.get("element"), "Motes")
heroes = []
for f in ("concepts.json", "new_heroes.json", "creatures.json"):
    heroes += json.load(open(os.path.join(HERE, "concepts", f)))
rows = [(c["id"], motif(c)) for c in heroes]
cs = ["// GENERATED by docs/sigilbound/sigfx.py from each approved design's fx line. Do not edit by hand.",
      "using System.Collections.Generic;", "", "namespace Sigilbound.Core", "{",
      "    public enum Motif { " + ", ".join(sorted({m for m, _ in KEYS} | set(DEFAULT.values()) | {FALLBACK[0]})) + " }", "",
      "    public static class HeroSignatures", "    {",
      "        public static readonly Dictionary<string, Motif> Table = new Dictionary<string, Motif>", "        {"]
cs += [f'            ["{i}"] = Motif.{m},' for i, m in rows]
# Heroes in a gown or robe (blenderforge/kit_cloth.py makes them one): they idle upright, since a
# wide fighting stance stretches the skirt sideways.
def gowned(c):
    o = c.get("outfit") or {}
    t = " ".join([str(c.get("weapon", ""))] + [str(k) for k in c.get("kit", [])] + [str(x) for x in (o.get("acc") or [])] + [str(o.get("body", ""))]).lower()
    return bool(re.search(r"\b(robe|skirt|dress|gown)s?\b", t)) or str(o.get("legs", "")).startswith("none")
gown = sorted(c["id"] for c in heroes if gowned(c))
cs += ["        };", "        // Heroes wearing a gown or robe: they idle upright (a wide stance stretches the skirt).",
       "        public static readonly HashSet<string> Gowned = new HashSet<string> { " + ", ".join(f'"{i}"' for i in gown) + " };"]
cs += ["        public static Motif Of(string id, Element el) => Table.TryGetValue(id ?? \"\", out var m) ? m : el switch",
       "        {", "            Element.Flame => Motif.Embers, Element.Gale => Motif.Wind, Element.Tide => Motif.Water, Element.Light => Motif.Motes, _ => Motif.Wisps,",
       "        };", "    }", "}", ""]
out = os.path.join(HERE, "..", "..", "unity", "Assets", "Sigilbound", "Core", "Kit", "HeroSignatures.cs")
open(out, "w").write("\n".join(cs))
print(len(gown), "gowned;", len(rows), "heroes:", dict(collections.Counter(m for _, m in rows).most_common()))
