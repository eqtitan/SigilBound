"""Hero uniqueness audit (phase E, step 44). Plain Python 3, no Blender needed.

    python3 audit.py            # rewrite docs/sigilbound/UNIQUE.md
    python3 audit.py --check    # CI: fail on a new near-twin, a stale fix-list entry, or a missing signature

Two heroes are near-twins when they share the base body, most of their kit (Jaccard >= 0.6) and a
similar palette (mean RGB distance of armour, cloth, hair and accent < 110). Today's twins are in
FIX_LIST; steps 46-50 work it down to nothing. A pair that is fixed must leave FIX_LIST, so the
list only shrinks, and a new twin fails CI.
"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
from signatures import SIGNATURES  # noqa: E402

KIT_JACCARD = 0.6
PALETTE_DIST = 110.0

# Near-twins found by the first audit (2026-11-25). Remove a pair once its heroes are told apart.
FIX_LIST = {
    ("hask", "brega"), ("silas", "saoirse"), ("nyx", "vesper"), ("tamsin", "sienna"),
    ("aurelia", "rhea"), ("brannoc", "kestrel"), ("morwenna", "aelira"), ("ulfgar", "dunstan"),
    ("malachar", "pyrrhus"), ("ulfgar", "aurelia"), ("maelis", "caspian"), ("tallow", "gideon"),
    ("dunstan", "tallow"), ("thrain", "kharra"), ("velka", "orla"), ("thrain", "hale"),
    ("malachar", "tallow"), ("morwenna", "kaelith"), ("bram", "dorian"), ("thrain", "ronan"),
    ("odo", "sorrel"), ("hask", "hobb"), ("kaito", "corwin"), ("hobb", "brega"), ("hask", "tallow"),
    ("lumen", "aurex"), ("sorrel", "bastian"), ("brega", "tallow"), ("aelira", "kaelith"),
    ("velka", "nerys"), ("rhea", "lucan"), ("tallow", "pyrrhus"), ("velka", "selene"),
    ("rowan", "faelan"), ("nerys", "selene"), ("dunstan", "rowan"), ("dunstan", "thessaly"),
    ("caspian", "rowan"), ("caspian", "faelan"), ("dunstan", "stormbearer"), ("seraphine", "lyra"),
    ("thessaly", "stormbearer"), ("malachar", "thessaly"), ("aurelia", "stormbearer"),
    ("malachar", "gideon"), ("nerys", "lyra"), ("aurelia", "dunstan"), ("dunstan", "gideon"),
}

WEAPONS = {"whip", "hammer", "shield", "staff", "orb", "sword", "katana", "daggers", "bow", "spear", "candle",
           "club", "lantern", "hook", "trident", "bell", "anchor", "net", "axe", "lute", "mirror", "gauntlets",
           "book", "fan"}
BRAWLERS = {"odo", "kettle", "gorrum", "thrain"}
SMALL_FOCUS = {"candle", "mirror", "bell", "orb", "lantern"}


def load_heroes():
    s = open(os.path.join(HERE, "quat.py")).read()
    i = s.index("HEROES = {")
    j = s.index("\n}\n", i)
    return eval(s[i + 9:j + 2], {"dict": dict})  # the literal dict only; quat.py itself needs Blender


def rgb(h):
    return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)) if h else (0, 0, 0)


def palette_dist(a, b):
    return sum(math.dist(rgb(a[k]), rgb(b[k])) for k in ("armor", "cloth", "hair", "accent")) / 4


def kit_jaccard(a, b):
    ka, kb = set(a["kit"]), set(b["kit"])
    return len(ka & kb) / len(ka | kb) if ka | kb else 1.0


def clips(hid, h):
    """Mirrors Core/Kit/HeroAnim.cs AnimStyle.For (the prop is the first weapon in the kit)."""
    prop = next((k for k in h["kit"] if k in WEAPONS), "")
    idle = "Idle_Neutral" if prop in SMALL_FOCUS else "Idle_Gun" if prop == "bow" else "Idle_Sword"
    strike = "punch/kick" if hid in BRAWLERS else "slash/punch" if prop == "daggers" \
        else "slash/kick" if prop in ("spear", "trident") else "slash x2/kick"
    return f"{idle}, {strike}"


def twins(H):
    ids = list(H)
    out = []
    for x in range(len(ids)):
        for y in range(x + 1, len(ids)):
            a, b = H[ids[x]], H[ids[y]]
            if a["base"] != b["base"]:
                continue
            jac, pd = kit_jaccard(a, b), palette_dist(a, b)
            if jac >= KIT_JACCARD and pd < PALETTE_DIST:
                out.append((ids[x], ids[y], jac, pd))
    return out


def problems(H, found):
    errs = []
    pairs = {(a, b) for a, b, _, _ in found}
    norm = {tuple(p) if p in pairs else (p[1], p[0]) for p in FIX_LIST}
    for a, b, jac, pd in found:
        if (a, b) not in norm:
            errs.append(f"new near-twin: {a} and {b} (same base, kit overlap {jac:.2f}, palette distance {pd:.0f})")
    for p in sorted(norm - pairs):
        errs.append(f"fixed, so remove from FIX_LIST in audit.py: {p[0]} and {p[1]}")
    for hid in H:
        if not SIGNATURES.get(hid):
            errs.append(f"no signature for {hid} (signatures.py)")
    for hid in SIGNATURES:
        if hid not in H:
            errs.append(f"signature for unknown hero {hid}")
    return errs


def write_doc(H, found):
    from collections import Counter
    bases = Counter(h["base"] for h in H.values())
    kit = Counter(k for h in H.values() for k in h["kit"])
    L = ["# Hero uniqueness audit", "",
         "Generated by `unity/Tools~/blenderforge/audit.py` (phase E, step 44). Do not edit by hand:",
         "change `quat.py` (models) or `signatures.py`, then run `python3 audit.py`. CI runs `audit.py --check`.", "",
         "**Near-twin rule:** same base body, kit overlap (Jaccard) of at least "
         f"{KIT_JACCARD}, and mean palette distance under {PALETTE_DIST:.0f} (RGB, over armour, cloth, hair, accent).", "",
         f"## Summary", "",
         f"- Heroes: {len(H)}. Base bodies: " + ", ".join(f"{b} {n}" for b, n in bases.most_common()) + ".",
         f"- Near-twin pairs: **{len(found)}** (the fix list for steps 46-50).",
         "- Most shared kit pieces: " + ", ".join(f"{k} {n}" for k, n in kit.most_common(10)) + ".",
         "- Clips: every hero plays the same few base clips, picked by its prop (steps 53-55 give each its own).", "",
         "## Fix list (near-twins)", "", "| Hero | Hero | Kit overlap | Palette distance | Shared kit |", "|---|---|---|---|---|"]
    for a, b, jac, pd in sorted(found, key=lambda t: (-t[2], t[3])):
        shared = ", ".join(sorted(set(H[a]["kit"]) & set(H[b]["kit"])))
        L.append(f"| {a} | {b} | {jac:.2f} | {pd:.0f} | {shared} |")
    L += ["", "## Every hero", "",
          "| Hero | Base | Palette (armour / cloth / hair / accent) | Kit | Height | Clips | Signature (target) |",
          "|---|---|---|---|---|---|---|"]
    for hid, h in H.items():
        pal = " / ".join(h[k] for k in ("armor", "cloth", "hair", "accent"))
        L.append(f"| {hid} | {h['base']} | {pal} | {', '.join(h['kit'])} | {h.get('height', 1.0):.2f} "
                 f"| {clips(hid, h)} | {SIGNATURES.get(hid, '')} |")
    path = os.path.join(REPO, "docs", "sigilbound", "UNIQUE.md")
    open(path, "w").write("\n".join(L) + "\n")
    return path


def main():
    H = load_heroes()
    found = twins(H)
    if "--check" in sys.argv:
        errs = problems(H, found)
        for e in errs:
            print("audit:", e)
        print(f"audit: {len(H)} heroes, {len(found)} near-twins on the fix list, {len(errs)} problems")
        sys.exit(1 if errs else 0)
    print("wrote", write_doc(H, found), f"({len(found)} near-twins)")


if __name__ == "__main__":
    main()
