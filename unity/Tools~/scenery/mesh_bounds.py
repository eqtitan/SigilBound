# Writes unity/Assets/Sigilbound/Core/SceneMeshes.Generated.cs: the footprint of every scenery mesh (base kit,
# story packs, image-to-3D landmarks) so Core/SceneGen can test placements against the cameras without Unity.
#   python mesh_bounds.py            (run after make_props.py, make_landmarks.py or i3d_landmark.py)
# Per mesh: xz radius around the pivot (yaw-proof), that radius above 35 % of its height, lowest and highest y, triangles.
import os, struct, glob
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
UNITY = os.path.normpath(os.path.join(HERE, "..", ".."))
RES = os.path.join(UNITY, "Assets", "Resources", "Scenery")
OUT = os.path.join(UNITY, "Assets", "Sigilbound", "Core", "SceneMeshes.Generated.cs")


def read_sbp(path):
    """SBP1 kit files (Client/SceneryKit.Parse): yields (name, positions (n,3), triangles)."""
    b = open(path, "rb").read(); o = 0
    assert b[:4] == b"SBP1"; o = 4
    count, = struct.unpack_from("<i", b, o); o += 4
    for _ in range(count):
        ln = b[o]; o += 1; name = b[o:o + ln].decode(); o += ln
        vc, = struct.unpack_from("<i", b, o); o += 4; subs = b[o]; o += 1
        ic = struct.unpack_from("<%di" % subs, b, o); o += 4 * subs
        lo = np.array(struct.unpack_from("<3f", b, o)); sz = np.array(struct.unpack_from("<3f", b, o + 12)); o += 24
        raw = np.frombuffer(b, dtype=np.uint8, count=vc * 11, offset=o).reshape(vc, 11); o += vc * 11
        q = raw[:, :6].copy().view("<i2").astype(np.float64)
        pos = lo + (q + 32768) / 65535.0 * sz
        tris = sum(ic) // 3
        o += 2 * sum(ic)
        yield name, pos, tris


def read_sbl(path):
    """SBL1 image-to-3D landmark files (Client/SceneryKit.ParseLandmark)."""
    b = open(path, "rb").read()
    assert b[:4] == b"SBL1"
    o = 4; ln = b[o]; o += 1; name = b[o:o + ln].decode(); o += ln
    vc, ic = struct.unpack_from("<ii", b, o); o += 8
    lo = np.array(struct.unpack_from("<3f", b, o)); sz = np.array(struct.unpack_from("<3f", b, o + 12)); o += 24
    raw = np.frombuffer(b, dtype=np.uint8, count=vc * 13, offset=o).reshape(vc, 13)
    q = raw[:, :6].copy().view("<i2").astype(np.float64)
    return name, lo + (q + 32768) / 65535.0 * sz, ic // 3


def main():
    rows = {}
    for f in ("props.bytes", "story_act1.bytes", "story_act2.bytes"):
        p = os.path.join(RES, f)
        if not os.path.exists(p): continue
        for name, pos, tris in read_sbp(p):
            rows[name] = (pos, tris, f.split(".")[0])
    for p in sorted(glob.glob(os.path.join(RES, "Landmarks", "*.bytes"))):
        name, pos, tris = read_sbl(p)
        rows[name] = (pos, tris, "i3d")          # an image-to-3D landmark replaces the procedural mesh of that name
    lines = []
    for name in sorted(rows):
        pos, tris, src = rows[name]
        rad = np.sqrt(pos[:, 0] ** 2 + pos[:, 2] ** 2); y0, y1 = pos[:, 1].min(), pos[:, 1].max()
        tall = pos[:, 1] > y0 + 0.35 * (y1 - y0)
        r, r2 = float(rad.max()), float(rad[tall].max()) if tall.any() else float(rad.max())
        lines.append(f'            ["{name}"] = new MeshBox({r:.2f}f, {r2:.2f}f, {y0:.2f}f, {y1:.2f}f, {tris}, "{src}"),')
    src = (
        "// GENERATED by unity/Tools~/scenery/mesh_bounds.py from Resources/Scenery/*.bytes and Landmarks/*.bytes. Do not edit.\n"
        "// Each scenery mesh's footprint: xz radius around its pivot (any yaw), lowest and highest y, triangles, source pack.\n"
        "using System.Collections.Generic;\n\n"
        "namespace Sigilbound.Core\n{\n"
        "    public readonly struct MeshBox\n    {\n"
        "        // R: the whole footprint; RTall: the part above 35 % of its height (a weir or a root flare is low, the tower narrow).\n"
        "        public readonly float R, RTall, Y0, Y1; public readonly int Tris; public readonly string Pack;\n"
        "        public MeshBox(float r, float rTall, float y0, float y1, int tris, string pack) { R = r; RTall = rTall; Y0 = y0; Y1 = y1; Tris = tris; Pack = pack; }\n"
        "    }\n\n"
        "    public static partial class SceneMeshes\n    {\n"
        "        public static readonly Dictionary<string, MeshBox> All = new Dictionary<string, MeshBox>\n        {\n"
        + "\n".join(lines) + "\n        };\n    }\n}\n")
    open(OUT, "w", newline="\n").write(src)
    print("wrote", OUT, len(rows), "meshes")


if __name__ == "__main__":
    main()
